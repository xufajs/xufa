// @xufa/fun: a functional library of plain functions that work on any value (lists, strings, objects, iterables, one
// item), curried, with `_` to hold an argument's place, and operators classes can take part in. With no dependencies.
//
//   import { getAtPath, map, sum, subtract, _ } from '@xufa/fun';
//   getAtPath({ a: { b: [1, 2] } }, 'a.b[1]');  // 2
//   map({ x: 1, y: 2 }, (n) => n * 2);           // [2, 4]
//   sum([1, 2, 3]);                              // 6
//   subtract(_, 1)(5);                           // 4
//
// Its functions are also the fallback methods of expressions of @xufa/expression (Engine option `methods`):
// prices.sum(), ages.median(), doc.getAtPath('a.b').
