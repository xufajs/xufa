// Writes packages/html/lib/dom/clobber-names.js: the names of the properties of document and of a <form> in Chrome
// (through @xufa/browser) and in jsdom when given, so the DOM of @xufa/html has them too. A sanitizer (DOMPurify) drops
// an id or name whose value is one of them: in a browser such an element would clobber that property.
//
// node tools/port-purify/clobber-names.js [<jsdom folder>]
import fs from 'node:fs';
import { createRequire } from 'node:module';
import path from 'node:path';
import { chromium, findBrowser } from '@xufa/browser';

const [jsdomDir] = process.argv.slice(2);
const OUT = path.join(import.meta.dirname, '../../packages/html/lib/dom/clobber-names.js');

// All the names of an object: own and inherited, enumerable or not, but those of Object.prototype.
function namesOf(object) {
  const names = new Set();
  for (let o = object; o && o !== Object.prototype; o = Object.getPrototypeOf(o)) {
    for (const name of Object.getOwnPropertyNames(o)) names.add(name);
  }
  // eslint-disable-next-line guard-for-in
  for (const name in object) names.add(name);
  return [...names];
}

const browser = await chromium.launch({ executablePath: findBrowser() });
const page = await (await browser.newContext()).newPage();
await page.goto('about:blank');
const chrome = await page.evaluate(`(() => {
  const namesOf = ${namesOf.toString()};
  return { document: namesOf(document), form: namesOf(document.createElement('form')) };
})()`);
await browser.close();

const sets = { document: new Set(chrome.document), form: new Set(chrome.form) };
let from = 'Chrome';
if (jsdomDir) {
  const { JSDOM } = createRequire(path.join(path.resolve(jsdomDir), 'package.json'))('./lib/api.js');
  const { document } = new JSDOM('').window;
  for (const name of namesOf(document)) sets.document.add(name);
  for (const name of namesOf(document.createElement('form'))) sets.form.add(name);
  from = 'Chrome and jsdom';
}
const list = (set) =>
  [...set]
    .sort()
    .map((name) => `  '${name}',`)
    .join('\n');
fs.writeFileSync(
  OUT,
  `// Generated by tools/port-purify/clobber-names.js from ${from}: do not edit, run the tool.\n` +
    '// The names of the properties of document and of a <form> in browsers.\n\n' +
    `export const DOCUMENT_NAMES = [\n${list(sets.document)}\n];\n\nexport const FORM_NAMES = [\n${list(sets.form)}\n];\n`
);
console.log(`clobber-names: ${sets.document.size} names of document, ${sets.form.size} of a form (${from})`);
