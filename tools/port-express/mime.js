// Writes packages/http/lib/mime-db.js: the types by extension and the charsets of mime-db, as mime-types (the
// version Express 5 uses, a devDependency of @xufa/express) reads them, so that res.type(), res.set('Content-Type'),
// sendFile and static files answer what Express answers; and the types mime-db says are compressible or not (as
// compressible reads them, for @xufa/http/compression).
//   node tools/port-express/mime.js
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(path.join(root, 'packages/express/package.json'));
const mime = require('mime-types');
const requireFromMime = createRequire(require.resolve('mime-types'));
const db = requireFromMime('mime-db');
const versions = {
  mimeTypes: require('mime-types/package.json').version,
  mimeDb: requireFromMime('mime-db/package.json').version,
};

const extensions = Object.keys(mime.types).sort();
const charsets = Object.keys(db)
  .filter((type) => db[type].charset)
  .sort();
const compressible = Object.keys(db)
  .filter((type) => db[type].compressible !== undefined)
  .sort();
const lines = [
  `// Generated by tools/port-express/mime.js from mime-db ${versions.mimeDb} (MIT License, (c) Jonathan Ong and Douglas`,
  `// Christopher Wilson) as mime-types ${versions.mimeTypes} reads it: do not edit, run the tool.`,
  '',
  '// The type of each extension.',
  'export const TYPES = {',
  ...extensions.map((extension) => `  ${JSON.stringify(extension)}: ${JSON.stringify(mime.types[extension])},`),
  '};',
  '',
  '// The extensions of each type, the first the one mime-types gives (extension()).',
  'export const EXTENSIONS = {',
  ...Object.keys(mime.extensions)
    .sort()
    .map((type) => `  ${JSON.stringify(type)}: ${JSON.stringify(mime.extensions[type])},`),
  '};',
  '',
  '// The charset of the types that have one (text/* are UTF-8 without being here).',
  'export const CHARSETS = {',
  ...charsets.map((type) => `  ${JSON.stringify(type)}: ${JSON.stringify(db[type].charset)},`),
  '};',
  '',
  '// The types mime-db says are compressible (true) or not (false); the others are by their name (compressible()).',
  'export const COMPRESSIBLE = {',
  ...compressible.map((type) => `  ${JSON.stringify(type)}: ${db[type].compressible},`),
  '};',
  '',
];
fs.writeFileSync(path.join(root, 'packages/http/lib/mime-db.js'), lines.join('\n'));
console.log(
  `${extensions.length} extensions, ${charsets.length} charsets, ${compressible.length} compressible or not (mime-db ${versions.mimeDb})`
);
